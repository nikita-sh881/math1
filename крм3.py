def det3(m):
    a, b, c = m[0]
    d, e, f = m[1]
    g, h, i = m[2]
    return (a * (e * i - f * h)
          - b * (d * i - f * g)
          + c * (d * h - e * g))


def print_matrix(A, b, title="Система"):
    print(f"\n{title}:")
    for i in range(3):
        row = "  | " + "  ".join(f"{A[i][j]:>6}" for j in range(3)) + " |"
        if i == 1:
            print(row + f"   | x{i + 1} |   | {b[i]:>6} |")
        else:
            print(row + f"   | x{i + 1} |   | {b[i]:>6} |")


def print_det3(m, name="Δ"):
    a, b, c = m[0]
    d, e, f = m[1]
    g, h, i = m[2]

    print(f"  {name} = | {a:>4}  {b:>4}  {c:>4} |")
    print(f"       | {d:>4}  {e:>4}  {f:>4} |")
    print(f"       | {g:>4}  {h:>4}  {i:>4} |")

    t1 = a * (e * i - f * h)
    t2 = b * (d * i - f * g)
    t3 = c * (d * h - e * g)

    print(f"  Разложение по первой строке:")
    print(f"    {name} = {a}*({e}*{i} - {f}*{h}) - {b}*({d}*{i} - {f}*{g}) + {c}*({d}*{h} - {e}*{g})")
    print(f"    {name} = {a}*({e * i} - {f * h}) - {b}*({d * i} - {f * g}) + {c}*({d * h} - {e * g})")
    print(f"    {name} = {a}*({e * i - f * h}) - {b}*({d * i - f * g}) + {c}*({d * h - e * g})")
    print(f"    {name} = {t1} - {t2} + {t3} = {t1 - t2 + t3}")
    return t1 - t2 + t3

def replace_column(A, b, col):
    M = [row[:] for row in A]
    for i in range(3):
        M[i][col] = b[i]
    return M

def cramer3_detailed(A, b):
    print("\n" )
    print("ШАГ 1. Главный определитель Δ")
    D = print_det3(A, "Δ")

    if D == 0:
        raise ValueError("Δ = 0 → система не имеет единственного решения "
                         "(либо несовместна, либо бесконечно много решений).")

    deltas = []
    for k in range(3):
        print("\n")
        print(f"ШАГ {k + 2}. Определитель Δ{k + 1} "
              f"(столбец {k + 1} заменён на b)")
        print("=" * 55)
        Mk = replace_column(A, b, k)
        Dk = print_det3(Mk, f"Δ{k + 1}")
        deltas.append(Dk)

    print("\n")
    print("ШАГ 5. Формулы Крамера: xi = Δi / Δ")
    x = []
    for k in range(3):
        xi = deltas[k] / D
        x.append(xi)
        print(f"  x{k + 1} = Δ{k + 1} / Δ = {deltas[k]} / {D} = {xi:.6g}")

    return x

def read_natural(prompt):
    while True:
        s = input(prompt).strip()
        if not s.isdigit() or int(s) == 0:
            print("  Ошибка: нужно натуральное число (целое > 0). Попробуйте снова.")
            continue
        return int(s)

def read_matrix():
    A = []
    print("\nВведите коэффициенты матрицы A (3 строки по 3 натуральных числа):")
    for i in range(3):
        row = []
        for j in range(3):
            row.append(read_natural(f"  A[{i + 1}][{j + 1}] = "))
        A.append(row)

    print("Введите столбец свободных членов b (3 натуральных числа):")
    b = [read_natural(f"  b[{i + 1}] = ") for i in range(3)]
    return A, b

